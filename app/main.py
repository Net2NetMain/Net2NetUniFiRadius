@app.delete('/api/{collection}/{item_id}', dependencies=[Depends(admin)])
def delete_record(collection: str, item_id: int):
    if collection not in ('users', 'profiles', 'nas'):
        raise HTTPException(404)
    return mutate(f'DELETE FROM {collection} WHERE id=?', (item_id,), item_id)


def accounting_records():
    records = []
    # FreeRADIUS detail files contain accounting only, never authentication passwords.
    root = DATA / 'accounting'
    for path in sorted(root.glob('*/detail-*'), key=lambda p: p.stat().st_mtime)[-20:]:
        with path.open('rb') as stream:
            stream.seek(max(0, path.stat().st_size - 512_000))
            text = stream.read().decode(errors='replace')
        for block in re.split(r'\n\s*\n', text):
            record = {}
            for line in block.splitlines():
                match = re.match(r'\s+([A-Za-z0-9-]+) = (.*)', line)
                if match:
                    record[match[1]] = match[2].strip('"')
            if 'Acct-Session-Id' in record:
                records.append(record)
    return records[-2000:]


@app.get('/api/accounting', dependencies=[Depends(admin)])
def accounting():
    sessions = {}
    for r in accounting_records():
        nas = r.get('NAS-IP-Address', r.get('Packet-Src-IP-Address', ''))
        key = (nas, r['Acct-Session-Id'])
        sessions[key] = {'session_id': r['Acct-Session-Id'], 'username': r.get('User-Name', ''),
                         'nas': nas, 'mac': r.get('Calling-Station-Id', ''),
                         'state': r.get('Acct-Status-Type', ''), 'seconds': r.get('Acct-Session-Time', '0'),
                         'timestamp': r.get('Timestamp', '')}
    return list(sessions.values())[-200:][::-1]


@app.get('/api/ca', dependencies=[Depends(admin)])
def ca():
    path = DATA / 'certs/ca.pem'
    if not path.exists():
        raise HTTPException(404, 'CA is generated on first Docker start')
    return FileResponse(path, filename='net2net-unifi-ca.pem', media_type='application/x-pem-file')


@app.get('/api/backup', dependencies=[Depends(admin)])
def backup():
    import io
    import zipfile
    with LOCK:
        target = DATA / 'backup.sqlite'
        with db() as source, closing(sqlite3.connect(target)) as dest:
            source.backup(dest)
        output = io.BytesIO()
        with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as archive:
            archive.write(target, 'unifi.db')
            archive.write(DATA / 'secret.key', 'secret.key')
            for path in (DATA / 'certs').glob('*'):
                if path.is_file():
                    archive.write(path, 'certs/' + path.name)
        target.unlink()
    return Response(output.getvalue(), media_type='application/zip',
                    headers={'Content-Disposition': 'attachment; filename=net2net-unifi-backup.zip'})


