DATA = Path(os.environ.get('DATA_DIR', './data'))
RADIUS = os.environ.get('RADIUS_CONFIG', '')
LOCK = threading.RLock()
RADIUS_PROCESS = None
WEB = Path(__file__).resolve().parents[1] / 'web'


@contextmanager
def db():
    with closing(sqlite3.connect(DATA / 'unifi.db', timeout=15)) as connection:
        with connection:
            connection.row_factory = sqlite3.Row
            connection.execute('PRAGMA foreign_keys=ON')
            yield connection


def encryptor():
    return Fernet((DATA / 'secret.key').read_bytes())


def password_hash(password, salt):
    return hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()


def initialize():
    DATA.mkdir(parents=True, exist_ok=True)
    key = DATA / 'secret.key'
    if not key.exists():
        key.write_bytes(Fernet.generate_key())
    key.chmod(0o600)
    with db() as c:
        c.executescript('''
        CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS profiles (id INTEGER PRIMARY KEY, name TEXT UNIQUE NOT NULL,
          vlan INTEGER NOT NULL CHECK(vlan BETWEEN 1 AND 4094));
        CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, username TEXT UNIQUE NOT NULL,
          display_name TEXT NOT NULL, password TEXT NOT NULL,
          profile_id INTEGER NOT NULL REFERENCES profiles(id), status TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS nas (id INTEGER PRIMARY KEY, name TEXT UNIQUE NOT NULL,
          address TEXT UNIQUE NOT NULL, secret TEXT NOT NULL);
        CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, expires INTEGER NOT NULL);
        CREATE TABLE IF NOT EXISTS attempts (address TEXT PRIMARY KEY, failures INTEGER, until_at INTEGER);
        ''')
        if not c.execute("SELECT 1 FROM settings WHERE key='admin_hash'").fetchone():
            password = os.environ.get('ADMIN_PASSWORD', '')
            if len(password) < 12 or password.startswith('replace-'):
                raise RuntimeError('Set ADMIN_PASSWORD to a unique password of at least 12 characters')
            salt = secrets.token_hex(16)
            c.executemany('INSERT INTO settings VALUES (?,?)',
                          [('admin_salt', salt), ('admin_hash', password_hash(password, salt))])
    (DATA / 'unifi.db').chmod(0o600)


def quoted(value):
    # Only printable values reach the generator. Quote both config metacharacters.
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def literal(value):
    # FreeRADIUS single-quoted values preserve literal %{...} in passwords.
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"


def render_config(c):
    users = ['# Generated by Net2Net UniFi RADIUS. Manage in the portal.\n']
    for row in c.execute('SELECT u.*,p.vlan FROM users u JOIN profiles p ON p.id=u.profile_id ORDER BY u.id'):
        if row['status'] != 'active':
            # Explicit rejection also overrides a resumed EAP session on reauth.
            users.append(f"{quoted(row['username'])} Auth-Type := Reject\n\n")
            continue
        password = encryptor().decrypt(row['password'].encode()).decode()
        users.append(f"{quoted(row['username'])} Cleartext-Password := {literal(password)}\n"
                     f"\tTunnel-Type := VLAN,\n\tTunnel-Medium-Type := IEEE-802,\n"
                     f"\tTunnel-Private-Group-Id := {quoted(str(row['vlan']))},\n"
                     "\tAcct-Interim-Interval := 300\n\n")
    clients = ['# Generated by Net2Net UniFi RADIUS\n']
    # No catch-all client or default shared secret. Register each AP/switch/NAS.
    for row in c.execute('SELECT * FROM nas ORDER BY id'):
        secret = encryptor().decrypt(row['secret'].encode()).decode()
        clients.append(f"client net2net_{row['id']} {{\n ipaddr = {row['address']}\n"
                       f" secret = {quoted(secret)}\n require_message_authenticator = yes\n}}\n")
    return ''.join(users), ''.join(clients)


def apply_config(c):
    if not RADIUS:
        return
    users, clients = render_config(c)
    root = Path(RADIUS)
    targets = [(root / 'mods-config/files/authorize', users), (root / 'clients.conf', clients)]
    originals = [(p, p.read_bytes() if p.exists() else None) for p, _ in targets]
    try:
        for target, content in targets:
            temp = target.with_suffix('.new')
            temp.write_text(content, encoding='utf-8')
            temp.chmod(0o640)
            if os.name != 'nt':
                import shutil
                shutil.chown(temp, group='freerad')
            temp.replace(target)
        check = subprocess.run(['freeradius', '-C'], capture_output=True, timeout=20)
        if check.returncode:
            raise RuntimeError('FreeRADIUS configuration validation failed')
        restart_radius()
    except Exception:
        for target, original in originals:
            if original is None:
                target.unlink(missing_ok=True)
            else:
                target.write_bytes(original)
        if RADIUS_PROCESS is not None:
            restart_radius()
        raise


def restart_radius():
    global RADIUS_PROCESS
    if RADIUS_PROCESS is not None:
        RADIUS_PROCESS.terminate()
        try:
            RADIUS_PROCESS.wait(timeout=5)
        except subprocess.TimeoutExpired:
            RADIUS_PROCESS.kill()
            RADIUS_PROCESS.wait(timeout=5)
    RADIUS_PROCESS = subprocess.Popen(['freeradius', '-f'])
    time.sleep(0.3)
    if RADIUS_PROCESS.poll() is not None:
        raise RuntimeError('FreeRADIUS failed to start')


@asynccontextmanager
async def lifespan(app):
    initialize()
    if RADIUS:
        with db() as c:
            apply_config(c)
    try:
        yield
    finally:
        if RADIUS_PROCESS is not None:
            RADIUS_PROCESS.terminate()
            RADIUS_PROCESS.wait(timeout=10)


app = FastAPI(title='Net2Net UniFi RADIUS', version='0.2.2', lifespan=lifespan)


def admin(request: Request):
    token = request.cookies.get('net2net_unifi', '')
    with db() as c:
        row = c.execute('SELECT 1 FROM sessions WHERE token=? AND expires>?',
                        (hashlib.sha256(token.encode()).hexdigest(), time.time())).fetchone()
    if not row:
        raise HTTPException(401, 'Sign in to continue')
    if request.method not in ('GET', 'HEAD') and request.headers.get('X-Net2Net-Request') != 'portal':
        raise HTTPException(403, 'Missing request verification header')


class Login(BaseModel):
    password: str = Field(max_length=256)


class Profile(BaseModel):
    name: str = Field(min_length=2, max_length=80)
    vlan: int = Field(ge=1, le=4094)


class User(BaseModel):
    username: str = Field(pattern=r'^[a-zA-Z0-9_.@-]{3,100}$')
    display_name: str = Field(min_length=2, max_length=100)
    password: str = Field(default='', max_length=128)
    profile_id: int
    status: str = Field(default='active', pattern=r'^(active|suspended|disabled)$')

    @field_validator('password')
    @classmethod
    def printable(cls, value):
        if value and (len(value) < 7 or not value.isascii() or not value.isprintable()):
            raise ValueError('Use at least 7 printable ASCII characters')
        return value


class Nas(BaseModel):
    name: str = Field(min_length=2, max_length=80)
    address: str
    secret: str = Field(default='', max_length=128)

    @field_validator('address')
    @classmethod
    def valid_ip(cls, value):
        return str(ipaddress.ip_address(value))

    @field_validator('secret')
    @classmethod
    def printable(cls, value):
        if value and not re.fullmatch(r'[A-Za-z0-9_.!@#\-]{16,128}', value):
            raise ValueError('Use 16+ characters: letters, numbers, underscore, dot, ! @ # or hyphen')
        return value


@app.get('/api/health')
def health():
    if RADIUS and (RADIUS_PROCESS is None or RADIUS_PROCESS.poll() is not None):
        raise HTTPException(503, 'RADIUS service is stopped')
    return {'status': 'ok', 'product': 'Net2Net UniFi RADIUS', 'version': '0.2.2',
            'radius_configured': bool(RADIUS)}


@app.post('/api/login')
def login(body: Login, request: Request, response: Response):
    address = request.client.host
    with db() as c:
        attempt = c.execute('SELECT * FROM attempts WHERE address=?', (address,)).fetchone()
        if attempt and attempt['failures'] >= 5 and attempt['until_at'] > time.time():
            raise HTTPException(429, 'Too many attempts. Try again in 5 minutes.')
        settings = dict(c.execute('SELECT key,value FROM settings').fetchall())
        if not hmac.compare_digest(password_hash(body.password, settings['admin_salt']), settings['admin_hash']):
            failures = attempt['failures'] + 1 if attempt and attempt['until_at'] > time.time() else 1
            c.execute('INSERT OR REPLACE INTO attempts VALUES (?,?,?)', (address, failures, int(time.time()) + 300))
            c.commit()
            raise HTTPException(401, 'Incorrect password')
        c.execute('DELETE FROM attempts WHERE address=?', (address,))
        c.execute('DELETE FROM sessions WHERE expires<?', (time.time(),))
        token = secrets.token_urlsafe(32)
        c.execute('INSERT INTO sessions VALUES (?,?)',
                  (hashlib.sha256(token.encode()).hexdigest(), int(time.time()) + 28800))
    response.set_cookie('net2net_unifi', token, httponly=True, samesite='strict',
                        secure=request.url.scheme == 'https', max_age=28800)
    return {'username': 'admin'}


@app.post('/api/logout', dependencies=[Depends(admin)])
def logout(request: Request, response: Response):
    with db() as c:
        c.execute('DELETE FROM sessions WHERE token=?',
                  (hashlib.sha256(request.cookies.get('net2net_unifi', '').encode()).hexdigest(),))
    response.delete_cookie('net2net_unifi')
    return {'ok': True}


@app.get('/api/state', dependencies=[Depends(admin)])
def state():
    with db() as c:
        return {'profiles': [dict(r) for r in c.execute('SELECT * FROM profiles ORDER BY name')],
                'users': [dict(r) for r in c.execute('SELECT id,username,display_name,profile_id,status FROM users ORDER BY username')],
                'nas': [dict(r) for r in c.execute('SELECT id,name,address FROM nas ORDER BY name')],
                'radius_configured': bool(RADIUS),
                'server_name': os.environ.get('RADIUS_SERVER_NAME', 'radius.net2net.local')}


def mutate(query, values, item_id=None):
    with LOCK, db() as c:
        try:
            result = c.execute(query, values)
            if item_id is not None and result.rowcount == 0:
                raise HTTPException(404, 'Record not found')
            apply_config(c)
        except sqlite3.IntegrityError:
            raise HTTPException(409, 'Name/address already exists, or the profile is still in use or missing')
        except (RuntimeError, OSError, subprocess.SubprocessError):
            raise HTTPException(503, 'RADIUS configuration could not be applied; changes were rolled back')
    return {'ok': True}


